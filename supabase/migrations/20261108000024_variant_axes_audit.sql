    update public.variants
       set size_option_id = v_size, option_ids = array[v_size], option_key = v_size::text
     where product_id = v_product and deleted_at is null and size_option_id is null;
    delete from public.product_attribute_values pav using public.attribute_defs d
     where pav.product_id = v_product and d.id = pav.attribute_id and d.code = 'pack_volume';
  end if;
end $$;

