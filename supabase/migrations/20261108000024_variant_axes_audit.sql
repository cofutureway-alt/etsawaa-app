 using public.categories c, audit_axes a, axis_ids x
 where c.id = ca.category_id and c.slug_en = a.slug and c.deleted_at is null
   and ((ca.attribute_id = x.color_id and not a.want_color
         and not exists (select 1 from public.variant_groups g join public.products p on p.id = g.product_id
                          where p.leaf_category_id = c.id and g.color_option_id is not null and g.deleted_at is null and p.deleted_at is null))
     or (ca.attribute_id = x.size_id and a.want_size is null
         and not exists (select 1 from public.variants v join public.products p on p.id = v.product_id
                          where p.leaf_category_id = c.id and v.size_option_id is not null and v.deleted_at is null and p.deleted_at is null)));

