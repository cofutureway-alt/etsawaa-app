declare
  v_product uuid := '527f81f2-3581-45de-9ea7-a074c5c51427';
  v_size uuid;
begin
  select o.id into v_size from public.attribute_options o join public.attribute_defs d on d.id = o.attribute_id
   where d.code = 'size' and d.is_variant_axis and d.category_id is null and o.code = 'wt_9000g';
  if exists (select 1 from public.products where id = v_product) and v_size is not null then
