export const ACHIEVEMENT_ICONS = Object.keys(GLYPHS);

/** Brand-aligned swatches offered in the editors (any #RRGGBB is accepted). */
export const ACHIEVEMENT_COLORS = ["#C8102E", "#D4A017", "#8C8C8C", "#B87333", "#1F7A4D", "#1D5FBF", "#6B3FA0", "#0E7C86", "#D9480F", "#1A1A1A"] as const;

export function AchievementGlyph({ icon, className = "size-5" }: { icon: string; className?: string }) {
  return (
    <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} strokeLinecap="round" strokeLinejoin="round"
      aria-hidden="true" className={className}>
      {GLYPHS[icon] ?? GLYPHS.award}
    </svg>
  );
}

/** Coloured disc with the glyph — how levels and badges appear everywhere. */
export function AchievementIcon({ icon, color, size = "md", title }: {
  icon: string;
  color: string;
  size?: "xs" | "sm" | "md" | "lg";
  title?: string;
}) {
  const box = { xs: "size-6", sm: "size-8", md: "size-11", lg: "size-14" }[size];
  const glyph = { xs: "size-3.5", sm: "size-4", md: "size-5.5", lg: "size-7" }[size];
  const safe = /^#[0-9A-Fa-f]{6}$/.test(color) ? color : "#C8102E";
  return (
    <span
      title={title}
      role={title ? "img" : undefined}
      aria-label={title}
      className={`${box} inline-flex shrink-0 items-center justify-center rounded-full`}
      style={{ backgroundColor: `${safe}1F`, color: safe, boxShadow: `inset 0 0 0 1.5px ${safe}55` }}
    >
      <AchievementGlyph icon={icon} className={glyph} />
    </span>
  );
}

/** Icon + colour chooser used by the level and badge editors. */
export function AchievementIconPicker({ icon, color, onIcon, onColor, iconLabel, colorLabel }: {
  icon: string;
  color: string;
  onIcon: (icon: string) => void;
  onColor: (color: string) => void;
  iconLabel: string;
  colorLabel: string;
}) {
  return (
    <div className="flex flex-col gap-3">
      <fieldset>
        <legend className="mb-1.5 text-sm font-bold text-text">{iconLabel}</legend>
        <div className="grid grid-cols-8 gap-1.5 sm:grid-cols-10">
          {ACHIEVEMENT_ICONS.map((key) => (
            <button
              key={key}
              type="button"
              onClick={() => onIcon(key)}
              aria-label={key}
              aria-pressed={icon === key}
              className={`flex aspect-square cursor-pointer items-center justify-center rounded-md border transition-colors ${
                icon === key ? "border-action bg-surface-tint text-action" : "border-border text-text-muted hover:border-action hover:text-action"
              }`}
            >
              <AchievementGlyph icon={key} className="size-5" />
            </button>
          ))}
        </div>
      </fieldset>
      <fieldset>
        <legend className="mb-1.5 text-sm font-bold text-text">{colorLabel}</legend>
        <div className="flex flex-wrap items-center gap-2">
          {ACHIEVEMENT_COLORS.map((c) => (
            <button
              key={c}
              type="button"
              onClick={() => onColor(c)}
              aria-label={c}
              aria-pressed={color.toLowerCase() === c.toLowerCase()}
              className={`size-8 cursor-pointer rounded-full border-2 ${color.toLowerCase() === c.toLowerCase() ? "border-text" : "border-transparent"}`}
              style={{ backgroundColor: c }}
            />
          ))}
          <input type="color" value={color} onChange={(e) => onColor(e.target.value)} aria-label={colorLabel}
            className="size-8 cursor-pointer rounded-full border border-border bg-transparent" />
        </div>
      </fieldset>
    </div>
  );
}
