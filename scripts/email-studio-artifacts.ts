import { mkdirSync, writeFileSync } from "node:fs";
import { EMAIL_CATALOG, emailSampleVariables } from "../app/lib/email/catalog";
import { compileEmailTemplate, renderEmailContent, validateContent } from "../app/lib/email/content";

const directory = "evidence/email-studio";
mkdirSync(directory, { recursive: true });
const ONLY = new Set(process.argv.slice(3));
const definitions = EMAIL_CATALOG.filter((t) => !ONLY.size || ONLY.has(t.key)).map((t) => {
  const result = validateContent(t.content, t.variables);
  if (!result.ok) throw new Error(`${t.key}:${result.reason}`);
  for (const locale of ["ar", "en"] as const) {
    const rendered = renderEmailContent(t.content[locale], locale, emailSampleVariables(locale, t.key));
    writeFileSync(`${directory}/${t.key.replace(/[:.]/g, "-")}-${locale}.html`, rendered.html);
  }
  return { ...t, html_ar: compileEmailTemplate(t.content.ar, "ar", t.variables), html_en: compileEmailTemplate(t.content.en, "en", t.variables) };
});
const sql = `-- Generated by scripts/email-studio-artifacts.ts from the reviewed bilingual catalogue.
-- Existing active/paused choices are retained. A re-run never overwrites studio edits.
begin;
with definitions as (
 select value d from jsonb_array_elements($email_catalog$${JSON.stringify(definitions)}$email_catalog$::jsonb)
)
insert into public.email_templates(key,name_ar,name_en,audience,variables,subject_ar,subject_en,html_ar,html_en,content_ar,content_en)
select d->>'key',d->>'name_ar',d->>'name_en',d->>'audience',d->'variables',
 d->'content'->'ar'->>'subject',d->'content'->'en'->>'subject',d->>'html_ar',d->>'html_en',d->'content'->'ar',d->'content'->'en'
from definitions
on conflict(key) do update set name_ar=excluded.name_ar,name_en=excluded.name_en,audience=excluded.audience,
 variables=excluded.variables,subject_ar=excluded.subject_ar,subject_en=excluded.subject_en,
 html_ar=excluded.html_ar,html_en=excluded.html_en,content_ar=excluded.content_ar,content_en=excluded.content_en,
 version=email_templates.version+1,revision=email_templates.revision+1,updated_at=now()
where email_templates.content_ar is null and email_templates.content_en is null;
insert into public.email_template_versions(template_key,version,snapshot)
select key,version,to_jsonb(t) from public.email_templates t where content_ar is not null on conflict do nothing;
commit;
`;
writeFileSync(process.argv[2] ?? "supabase/migrations/20261122000075_branded_email_catalog.sql", sql);
console.log(`Generated ${definitions.length} bilingual templates and ${definitions.length * 2} previews.`);
